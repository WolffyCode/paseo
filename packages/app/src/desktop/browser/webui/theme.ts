/** A withUnistyles mapping that colors a glyph with one of the WebUI colors. */
export function webUiColorProps(
  key: keyof WebUiColors,
): (theme: { webui: WebUiColors }) => { color: string } {
  return (theme) => ({ color: theme.webui[key] });
}

