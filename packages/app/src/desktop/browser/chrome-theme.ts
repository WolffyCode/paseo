/** The part of the app theme that holds Chrome's colors. */
export interface ChromeTheme {
  chrome: ChromeColors;
}

/** A withUnistyles mapping that colors a glyph with one of Chrome's colors. */
export function chromeColorProps(
  key: keyof ChromeColors,
): (theme: ChromeTheme) => { color: string } {
  return (theme) => ({ color: theme.chrome[key] });
}

